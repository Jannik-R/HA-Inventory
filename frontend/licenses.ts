import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import type { Plugin } from "vite";

/** Package root of a bundled module id inside node_modules (handles @scope/name), else undefined. */
const packageRoot = (id: string): string | undefined => {
  const path = id.split("?")[0].replace(/^\0/, "").replaceAll("\\", "/");
  const m = /^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(path);
  return m?.[1];
};

const licenseText = (root: string): string => {
  const file = readdirSync(root).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  // license files may use CRLF; the committed bundle is LF
  const text = file ? readFileSync(join(root, file), "utf8").replaceAll("\r\n", "\n") : "";
  return text.trim() || "(no license file in the package)";
};

/**
 * Writes THIRD_PARTY_LICENSES.txt next to the bundle: name, version, license and the license text of
 * every npm package that ends up in it. MIT, BSD and Apache require the notice with the code, and the
 * minifier drops the comments. Part of the build, so CI's "bundle equals a fresh build" covers it.
 */
export const thirdPartyLicenses = (): Plugin => ({
  name: "third-party-licenses",
  apply: "build",
  generateBundle(_, bundle) {
    const roots = new Set<string>();
    for (const out of Object.values(bundle)) {
      if (out.type !== "chunk") continue;
      for (const id of Object.keys(out.modules)) {
        const root = packageRoot(id);
        if (root) roots.add(root);
      }
    }
    const entries = [...roots]
      .map((root) => {
        const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
        return { pkg, root };
      })
      .sort((a, b) => a.pkg.name.localeCompare(b.pkg.name))
      .map(
        ({ pkg, root }) =>
          `${pkg.name} ${pkg.version} (${pkg.license ?? "see below"})\n\n${licenseText(root)}`,
      );
    this.emitFile({
      type: "asset",
      fileName: "THIRD_PARTY_LICENSES.txt",
      source:
        "Third-party software bundled in this directory (generated by the build).\n" +
        "The zxing-wasm package contains zxing-cpp (Apache-2.0).\n\n" +
        entries.join(`\n\n${"-".repeat(72)}\n\n`) +
        "\n",
    });
  },
});
